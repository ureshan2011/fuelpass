window.currentLang = 'en';

window.t = function(key) {
  if (window.currentLang === 'en') return key;
  if (langDict[key] && langDict[key][window.currentLang]) {
    return langDict[key][window.currentLang];
  }
  return key;
};

// Store original node values internally so we can translate back to English properly
document.addEventListener("DOMContentLoaded", () => {
  window.textNodesMap = [];
  window.attrNodesMap = [];
  
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
  let node;
  while(node = walker.nextNode()) {
    if(node.parentElement.tagName === 'SCRIPT' || node.parentElement.tagName === 'STYLE') continue;
    const text = node.nodeValue.trim();
    if(text && langDict[text]) {
      window.textNodesMap.push({ node: node, key: text, original: node.nodeValue });
    }
  }

  // Also collect input placeholders
  const inputs = document.querySelectorAll('input[placeholder]');
  inputs.forEach(input => {
    const text = input.getAttribute('placeholder').trim();
    if (text && langDict[text]) {
      window.attrNodesMap.push({ node: input, attr: 'placeholder', key: text });
    }
  });

  // Re-translate if language is cached or default not en
  applyPageTranslations(window.currentLang);
});

function applyPageTranslations(lang) {
  window.currentLang = lang;
  
  window.textNodesMap.forEach(item => {
    let tl = (lang === 'en') ? item.key : (langDict[item.key] && langDict[item.key][lang]) || item.key;
    item.node.nodeValue = item.original.replace(item.key, tl);
  });

  window.attrNodesMap.forEach(item => {
    let tl = (lang === 'en') ? item.key : (langDict[item.key] && langDict[item.key][lang]) || item.key;
    item.node.setAttribute(item.attr, tl);
  });

  document.documentElement.lang = lang;
}
